scratch('smoke_helpers')
c = root()
# revolve: knob profile on xz plane (sketch y -> model -z, so draw with negative y for +z)
k = comp('Knob')
s = sketch(k, 'xz', 'knob_prof')
poly(s, [(0, 0), (8, 0), (8, -6), (6, -8), (0, -8)])
knob = revolve(k, prof(s), 'z', name='KnobRev').bodies.item(0)
fillet(k, edges(knob, kind='circle', where=lambda e: mm(e.pointOnEdge)[2] > 7.9), 1, name='KnobTopFillet')
# grip notch + circular pattern
s3 = sketch(k, 'xy', 'notch')
crect(s3, 2, 2, 8, 0)
notch = extrude(k, prof(s3), 6, op='cut', name='Notch')
cpattern(k, notch, 'z', 12, name='NotchPattern')
# base plate with slot, hex, text, rect pattern of pins, mirror, combine, move/rotate
p = comp('Plate')
s4 = sketch(p, 'xy', 'plate')
rect(s4, 20, -15, 70, 15)
plate = extrude(p, prof(s4), 3, name='PlateExt').bodies.item(0)
s5 = sketch(p, face_end(plate, 'z', 'max'), 'feat')
slot(s5, *sp(s5, 30, 8), *sp(s5, 45, 8), 4)
rpoly(s5, 6, 6, *sp(s5, 60, 8))
extrude(p, [prof_at(s5, *sp(s5, 37.5, 8)), prof_at(s5, *sp(s5, 60, 8))], '-all', op='cut', name='SlotHex')
s6 = sketch(p, face_end(plate, 'z', 'max'), 'label')
x0, y0 = sp(s6, 25, -12); x1, y1 = sp(s6, 65, -2)
lbl = text(s6, 'MIC', 6, min(x0, x1), min(y0, y1), max(x0, x1), max(y0, y1))
extrude(p, lbl, 0.6, op='join', name='Label')
s7 = sketch(p, 'xy', 'pin', offset=3)
circle(s7, 2, 25, 10)
pin = extrude(p, prof(s7), 4, op='new', name='Pin').bodies.item(0)
rpattern(p, pin, 'x', 2, 5, 'y', 2, -5, name='PinPattern')
mirror(p, list(p.bRepBodies)[1:], 'xz', name='PinMirror')
combine(p, plate, list(p.bRepBodies)[1:], op='join', name='PinsJoin')
cube_s = sketch(c, 'xy', 'cube')
crect(cube_s, 5, 5)
cube = extrude(c, prof(cube_s), 5, name='Cube').bodies.item(0)
move(c, cube, 0, -30, 0, name='CubeMove')
rotate(c, cube, 'z', 45, name='CubeRot')
print('look', look(plate, 'Aluminum - Anodized'))
print('mat', material(plate, 'Aluminum'))
report()
out = os.path.join(OUT, 'plate.stl')
print('stl', export(p, out), os.path.getsize(out))
print('step', export(root(), os.path.join(OUT, 'all.step')))
